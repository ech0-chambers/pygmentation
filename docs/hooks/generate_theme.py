import json
import sys
from pathlib import Path

# Ensure local source tree takes precedence over any installed package
_SRC_DIR = str(Path(__file__).resolve().parent.parent.parent / "src")
if _SRC_DIR not in sys.path:
    sys.path.insert(0, _SRC_DIR)

import pygmentation as pyg  # noqa: E402
from pygmentation._fonts import FIRA_CODE_WOFF2_BASE64  # noqa: E402
from pygmentation.exporters import CssExporter, SvgExporter  # noqa: E402

# Configurable subset of schemes bundled for the interactive example card
EXAMPLE_SCHEMES: list[tuple[str, str]] = [
    ("nord", "Nord"),
    ("rose_pine", "Rosé Pine"),
    ("catppuccin", "Catppuccin"),
    ("twilight", "Twilight"),
    ("japanesque", "Japanesque"),
]


def generate_font_css() -> str:
    return f"""/* Embedded Fira Code font subset for documentation diagrams */
@font-face {{
  font-family: 'Fira Code';
  font-style: normal;
  font-weight: 400 700;
  src: url('data:font/woff2;charset=utf-8;base64,{FIRA_CODE_WOFF2_BASE64}') format('woff2');
}}
"""


def generate_main_theme_css(scheme_name: str = "nord") -> str:
    light = pyg.get_scheme(scheme_name, "light")
    dark = pyg.get_scheme(scheme_name, "dark")
    exporter = CssExporter()

    def extract_vars(scheme: pyg.ColorScheme) -> str:
        css = exporter.export(scheme)
        return css.split("{\n", 1)[1].rsplit("\n}", 1)[0]

    return f"""/* Main Documentation Theme Variables ({scheme_name}) */
[data-md-color-scheme="default"] {{
{extract_vars(light)}
}}

[data-md-color-scheme="slate"] {{
{extract_vars(dark)}
}}"""


def generate_example_schemes_css() -> str:
    exporter = CssExporter()
    blocks: list[str] = [
        "/* Scoped variables for interactive example card */",
    ]

    for name, _ in EXAMPLE_SCHEMES:
        light_scheme = pyg.get_scheme(name, "light")
        dark_scheme = pyg.get_scheme(name, "dark")

        light_vars = (
            exporter.export(light_scheme).split("{\n", 1)[1].rsplit("\n}", 1)[0]
        )
        dark_vars = (
            exporter.export(dark_scheme).split("{\n", 1)[1].rsplit("\n}", 1)[0]
        )

        # Light variant
        blocks.append(
            f'.pyg-example-card[data-scheme="{name}"][data-variant="light"],\n'
            f'.pyg-preview[data-scheme="{name}"][data-variant="light"] {{\n'
            f"{light_vars}\n"
            f"}}"
        )
        # Dark variant
        blocks.append(
            f'.pyg-example-card[data-scheme="{name}"][data-variant="dark"],\n'
            f'.pyg-preview[data-scheme="{name}"][data-variant="dark"] {{\n'
            f"{dark_vars}\n"
            f"}}"
        )
        # Default fallback (dark)
        blocks.append(
            f'.pyg-example-card[data-scheme="{name}"],\n'
            f'.pyg-preview[data-scheme="{name}"] {{\n'
            f"{dark_vars}\n"
            f"}}"
        )

    return "\n\n".join(blocks)


def compile_stylesheet(docs_dir: Path) -> str:
    src_dir = docs_dir / "stylesheets" / "src"

    material_theme_css = (src_dir / "material_theme.css").read_text(
        encoding="utf-8"
    )
    example_card_css = (src_dir / "example_card.css").read_text(
        encoding="utf-8"
    )
    palettes_css = (src_dir / "palettes.css").read_text(encoding="utf-8")

    font_css = generate_font_css()
    main_theme_css = generate_main_theme_css("nord")
    example_schemes_css = generate_example_schemes_css()

    header = (
        "/* ==========================================================================\n"
        "   Auto-generated by docs/hooks/generate_theme.py - DO NOT EDIT DIRECTLY\n"
        "   Edit source files in docs/stylesheets/src/ instead.\n"
        "   ========================================================================== */"
    )

    sections = [
        header,
        font_css.strip(),
        main_theme_css.strip(),
        material_theme_css.strip(),
        example_schemes_css.strip(),
        example_card_css.strip(),
        palettes_css.strip(),
    ]
    return "\n\n".join(sections) + "\n"


def generate_interactive_svg(source_path: Path, dest_path: Path) -> None:
    # Take the SVG graph used in the README, and change to use CSS variables so
    # it can respond to scheme changes
    if not source_path.exists():
        return

    content = source_path.read_text(encoding="utf-8")

    # Replace hardcoded colours with CSS variables
    replacements = [
        # Outer figure background
        ('style="fill: #ffffff"', 'style="fill: var(--clr-background)"'),
        # Axes background
        ('style="fill: #faf4ed"', 'style="fill: var(--clr-background-5)"'),
        # Legend box background
        (
            'style="fill: #f2ebe3; opacity: 0.5;',
            'style="fill: var(--clr-background-4); opacity: 0.85;',
        ),
        # All text, ticks, spines, labels
        ("#575279", "var(--clr-foreground)"),
        # Line 1 (primary accent)
        ("#b4637a", "var(--clr-accent1)"),
        # Line 2 (secondary accent)
        ("#ea9d34", "var(--clr-accent2)"),
        # Line 3 (tertiary accent)
        ("#286983", "var(--clr-accent3)"),
    ]

    for orig, repl in replacements:
        content = content.replace(orig, repl)

    dest_path.parent.mkdir(parents=True, exist_ok=True)
    dest_path.write_text(content, encoding="utf-8")


def generate_palette_svgs(docs_dir: Path) -> None:
    out_dir = docs_dir / "assets" / "palettes"
    available = pyg.registry.available
    total_expected = len(available) * 2

    sample_file = out_dir / "nord_dark.svg"
    if (
        out_dir.exists()
        and len(list(out_dir.glob("*.svg"))) == total_expected
        and sample_file.exists()
        and "@font-face" not in sample_file.read_text(encoding="utf-8")
        and "data-bg=" in sample_file.read_text(encoding="utf-8")
        and 'class="pyg-palette-swatch"' in sample_file.read_text(encoding="utf-8")
    ):
        return

    out_dir.mkdir(parents=True, exist_ok=True)
    exporter = SvgExporter(embed_font=False)
    for name in available:
        for variant in ("light", "dark"):
            svg_path = out_dir / f"{name}_{variant}.svg"
            scheme = pyg.get_scheme(name, variant)
            svg_path.write_text(exporter.export(scheme), encoding="utf-8")


def export_schemes_data(docs_dir: Path) -> None:
    out_file = docs_dir / "assets" / "data" / "schemes.json"
    out_file.parent.mkdir(parents=True, exist_ok=True)
    available_schemes = sorted(pyg.registry.available)
    out_file.write_text(json.dumps(available_schemes), encoding="utf-8")


def on_pre_build(config, **kwargs) -> None:
    docs_dir = Path(config["docs_dir"])

    # 1. Compile stylesheet from source files and dynamic schemes
    compiled_css = compile_stylesheet(docs_dir)
    out_css_path = docs_dir / "stylesheets" / "pygmentation.css"
    out_css_path.parent.mkdir(parents=True, exist_ok=True)
    out_css_path.write_text(compiled_css, encoding="utf-8")

    # 2. Generate interactive SVG graph snippet
    source_svg = Path(".swatches") / "sample_report.svg"
    dest_svg = docs_dir / "snippets" / "interactive_graph.svg"
    generate_interactive_svg(source_svg, dest_svg)

    # 3. Export scheme names list and pre-generate SVGs for palettes page
    export_schemes_data(docs_dir)
    generate_palette_svgs(docs_dir)
